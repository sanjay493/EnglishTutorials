#!/usr/bin/env node
// Generates _sidebar.md, PROGRESS.md, days/README.md and modules/*.md
// from ops/curriculum.json plus the front matter in days/*.md.
// Usage: node scripts/build-index.mjs [--check]
import path from 'node:path';
import {
  ROOT,
  readCurriculum,
  listLessons,
  lessonExists,
  escapeCell,
  writeIfChanged,
  readText,
  bar,
  pct,
} from './lib.mjs';

const checkOnly = process.argv.includes('--check');
const { course, modules, days } = readCurriculum();
const lessons = listLessons();
const byDay = new Map(lessons.map((l) => [l.day, l]));
const total = days.length;
const written = lessons.filter((l) => l.status === 'complete').length;

const stale = [];
function emit(file, content) {
  const target = path.join(ROOT, file);
  if (checkOnly) {
    const current = readText(target).replace(/\r\n/g, '\n');
    if (current !== content.replace(/\r\n/g, '\n')) {
      stale.push(file);
    }
    return;
  }
  if (writeIfChanged(target, content)) console.log(`Wrote ${file}`);
}

/* ------------------------------------------------------------------ sidebar */

const sidebar = [];
sidebar.push('- [Home](README.md)');
sidebar.push('- [Start here](START-HERE.md)');
sidebar.push('- [120-day plan](PLAN.md)');
sidebar.push('- [Progress](PROGRESS.md)');
sidebar.push('- [Style guide](STYLE-GUIDE.md)');
sidebar.push('- [Sources](SOURCES.md)');
sidebar.push('');
sidebar.push('---');
sidebar.push('');
for (const m of modules) {
  const moduleLessons = days.filter((d) => d.module === m.id && byDay.has(d.day));
  sidebar.push(`- **${m.id} · ${m.title} (${m.level})**`);
  sidebar.push(`  - [Overview](modules/${m.slug}.md)`);
  for (const d of moduleLessons) {
    const title = byDay.get(d.day).title || d.title;
    sidebar.push(`    - [Day ${d.day} · ${title}](days/day-${String(d.day).padStart(3, '0')}.md)`);
  }
}
sidebar.push('');
emit('_sidebar.md', sidebar.join('\n'));

/* ---------------------------------------------------------------- progress */

const next = days.find((d) => !byDay.has(d.day) || byDay.get(d.day).status !== 'complete');
const recent = [...lessons]
  .filter((l) => l.status === 'complete')
  .sort((a, b) => String(b.updated ?? '').localeCompare(String(a.updated ?? '')) || b.day - a.day)
  .slice(0, 5);

const progress = [];
progress.push('# Progress');
progress.push('');
progress.push('> Auto-generated by `node scripts/build-index.mjs` from `days/*.md`. Do not edit by hand.');
progress.push('');
progress.push('```text');
progress.push(`${course.title}`);
progress.push(`${bar(written, total)}  ${written}/${total} lessons  (${pct(written, total)})`);
progress.push('```');
progress.push('');
progress.push(`**${written} of ${total} lessons written.** ${total - written} still planned.`);
progress.push('');
progress.push('| Module | Level | Written | Progress |');
progress.push('| --- | --- | --- | --- |');
for (const m of modules) {
  const ids = days.filter((d) => d.module === m.id);
  const done = ids.filter((d) => byDay.get(d.day)?.status === 'complete').length;
  progress.push(
    `| [${m.id}. ${escapeCell(m.title)}](modules/${m.slug}.md) | ${m.level} | ${done}/${ids.length} | \`${bar(
      done,
      ids.length,
      12
    )}\` |`
  );
}
progress.push('');
progress.push('## Next up');
progress.push('');
if (next) {
  progress.push(
    `**Day ${next.day} · ${next.title}** — ${next.grammar}. Speaking: ${next.speaking}. Writing: ${next.writing}.`
  );
} else {
  progress.push('All 120 lessons are written. Time to run the final exam.');
}
progress.push('');
progress.push('## Recently added');
progress.push('');
if (recent.length) {
  progress.push('| Day | Lesson | Words | Updated |');
  progress.push('| --- | --- | --- | --- |');
  for (const l of recent) {
    progress.push(
      `| ${l.day} | [${escapeCell(l.title)}](${l.filePath}) | ${l.words ?? '—'} | ${l.updated ?? '—'} |`
    );
  }
} else {
  progress.push('No lessons yet.');
}
progress.push('');
progress.push('## How status is tracked');
progress.push('');
progress.push(
  'A lesson counts as written when its file exists in `days/` with `status: complete` in the front matter. Drafts are scaffolded with `node scripts/new-day.mjs <day>` and published by changing `draft` to `complete` after the checklist passes.'
);
progress.push('');
progress.push('Daily budget and run history: [`ops/run-log.jsonl`](ops/run-log.jsonl) and [`ops/token-budget.json`](ops/token-budget.json).');
progress.push('');
emit('PROGRESS.md', progress.join('\n'));

/* -------------------------------------------------------------- days index */

const dayIndex = [];
dayIndex.push('# All lessons');
dayIndex.push('');
dayIndex.push(
  `Every lesson in one table. New lessons are added at the bottom of the relevant module and appear here automatically.`
);
dayIndex.push('');
dayIndex.push(`**${written}/${total} written.**`);
dayIndex.push('');
dayIndex.push('| Day | Module | Level | Lesson | Grammar focus | Status |');
dayIndex.push('| --- | --- | --- | --- | --- | --- |');
for (const d of days) {
  const m = modules.find((x) => x.id === d.module);
  const exists = lessonExists(d.day);
  const title = byDay.get(d.day)?.title || d.title;
  const label = exists ? `[${escapeCell(title)}](day-${String(d.day).padStart(3, '0')}.md)` : escapeCell(title);
  dayIndex.push(
    `| ${d.day} | ${m.id} | ${m.level} | ${label} | ${escapeCell(d.grammar)} | ${
      byDay.get(d.day)?.status === 'complete' ? '✅' : exists ? '📝' : '⬜'
    } |`
  );
}
dayIndex.push('');
emit('days/README.md', dayIndex.join('\n'));

/* ------------------------------------------------------------ module pages */

for (const m of modules) {
  const ids = days.filter((d) => d.module === m.id);
  const done = ids.filter((d) => byDay.get(d.day)?.status === 'complete').length;
  const page = [];
  page.push(`# Module ${m.id} · ${m.title}`);
  page.push('');
  page.push(`**Level:** ${m.level} · **Days:** ${m.start}-${m.end} · **Written:** ${done}/${ids.length}`);
  page.push('');
  page.push(`> ${m.goal}`);
  page.push('');
  page.push('## Checkpoint');
  page.push('');
  page.push(m.checkpoint);
  page.push('');
  page.push('## Lessons');
  page.push('');
  page.push('| Day | Lesson | Grammar | Speaking | Writing | Status |');
  page.push('| --- | --- | --- | --- | --- | --- |');
  for (const d of ids) {
    const exists = lessonExists(d.day);
    const title = byDay.get(d.day)?.title || d.title;
    const label = exists ? `[${escapeCell(title)}](../days/day-${String(d.day).padStart(3, '0')}.md)` : escapeCell(title);
    page.push(
      `| ${d.day} | ${label} | ${escapeCell(d.grammar)} | ${escapeCell(d.speaking)} | ${escapeCell(
        d.writing
      )} | ${byDay.get(d.day)?.status === 'complete' ? '✅' : exists ? '📝' : '⬜'} |`
    );
  }
  page.push('');
  page.push('## How to work through this module');
  page.push('');
  page.push('1. Read each lesson once, then do the exercises without looking at the key.');
  page.push('2. Record the speaking lab on your phone; compare it with the model dialogue.');
  page.push('3. Keep every writing task in one folder, even the bad ones. You will revise them on the assessment day.');
  page.push('4. On the last day of the module, take the checkpoint without notes, then review only what you missed.');
  page.push('');
  page.push(
    'See [`PLAN.md`](../PLAN.md) for the full course map and [`SOURCES.md`](../SOURCES.md) for the references behind these lessons.'
  );
  page.push('');
  emit(`modules/${m.slug}.md`, page.join('\n'));
}

/* ------------------------------------------------------------------ result */

if (checkOnly) {
  if (stale.length) {
    console.error(`Out of date: ${stale.join(', ')}`);
    console.error('Run: node scripts/build-all.mjs');
    process.exitCode = 1;
  } else {
    console.log('Generated index files are up to date.');
  }
} else {
  console.log(`Index built: ${written}/${total} lessons complete.`);
}
